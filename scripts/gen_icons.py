# Build public/icons.js from Phosphor Icons (MIT) and the LINE mark from Simple Icons (CC0).
# Run: python3 gen_icons.py <icons-src dir> <out file>
import re, sys, json, pathlib
src, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
NAMES = {  # the app's name -> Phosphor's name
    "back": "arrow-left", "chev": "caret-right", "chevd": "caret-down", "person": "user", "wallet": "wallet",
    "check": "check", "x": "x", "clock": "clock", "bolt": "lightning", "refund": "arrow-u-up-left", "info": "info",
    "link": "globe-simple", "external": "arrow-square-out", "receipt": "receipt", "shield": "shield-check",
    "plane": "airplane-tilt", "tag": "tag", "doc": "newspaper", "food": "fork-knife", "help": "question",
    "trash": "trash", "list": "list-bullets", "lock": "lock", "logout": "sign-out",
}
FILL = {**NAMES, "check": "check-circle", "x": "x-circle", "refund": "arrow-counter-clockwise"}  # fuller shapes read better inside a tile
inner = lambda f: re.search(r"<svg[^>]*>(.*)</svg>", f.read_text(), re.S).group(1)
ph = src / "ph/package/assets"
data = {
    "bold": {k: inner(ph / "bold" / f"{v}-bold.svg") for k, v in NAMES.items()},
    "fill": {k: inner(ph / "fill" / f"{v}-fill.svg") for k, v in FILL.items()},
    "line": re.sub(r"<title>.*?</title>", "", inner(src / "si/package/icons/line.svg")),
}
lic = (src / "ph/package/LICENSE").read_text().strip()
out.write_text("// Generated by gen_icons.py. Icons: Phosphor Icons 2.1.1 (viewBox 0 0 256 256). LINE mark: Simple Icons (CC0, viewBox 0 0 24 24).\n/*\n"
               + lic + "\n*/\nwindow.ICONS = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(out, out.stat().st_size, "bytes")
